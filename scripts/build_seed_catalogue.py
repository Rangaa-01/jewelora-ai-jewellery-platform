def product(
    name: str,
    jtype: str,
    metal: str,
    stone: str,
    price: int,
    *,
    purity: str | None = None,
    weight: float,
    making: int,
    photos: list[Any],
    desc: str,
    tags: list[str],
    occasions: list[str],
    style: str,
    collections: list[str],
    stock: int = 3,
    featured: bool = False,
    new: bool = False,
    stone_ct: float | None = None,
    discount: int = 0,
    gender: str = "women",
    sizes: list[dict[str, Any]] | None = None,
    set_items: list[str] | None = None,
    variants: list[dict[str, Any]] | None = None,
    tryon: bool = True,
    seq: list[int] = [2300],
) -> dict[str, Any]:
    seq[0] += 1
    purity = (
        purity or {"gold": "18K", "white_gold": "18K", "rose_gold": "18K", "platinum": "950", "silver": "925"}[metal]
    )
    data: dict[str, Any] = {
        "sku": f"JM-{PREFIX[jtype]}-{seq[0]}",
        "name": name,
        "category": CATEGORY_BY_TYPE[jtype],
        "jewellery_type": jtype,
        "metal_type": metal,
        "purity": purity,
        "stone_type": stone,
        "base_price": price,
        "discount_percent": discount,
        "gross_weight_g": weight,
        "net_weight_g": round(weight * (0.92 if stone != "none" else 1.0), 1),
        "making_charges": making,
        "stock_quantity": stock,
        "gender": gender,
        "occasions": occasions,
        "tags": tags,
        "style": style,
        "is_featured": featured,
        "is_new": new,
        "collections": collections,
        "short_description": desc,
        "photos": photos,
        "variants": variants
        or [
            {
                "sku_suffix": SUFFIX[metal],
                "metal_type": metal,
                "stone_type": stone,
                "purity": purity,
                "is_default": True,
            }
        ],
    }
    if stone_ct:
        data["stone_weight_ct"] = stone_ct
    sizes = sizes if sizes is not None else SIZES_BY_TYPE.get(jtype)
    if sizes:
        data["sizes"] = sizes
    if set_items:
        data["set_items"] = set_items
    if not tryon:
        # The photo can't give a clean cut-out (dark stones on dark velvet); catalogue only.
        data["tryon"] = False
    return data


